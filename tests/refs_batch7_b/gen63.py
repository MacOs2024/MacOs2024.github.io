    out.append("Электрическая длина βl = 2π·l/λл" + dbs(360 * frac) + "° (" + dbs(2 * PI * frac) + " рад)")
    inf = False
    # полюс: холостой ход при sin = 0, КЗ при cos = 0, реактивная нагрузка при Z0·cos = X·sin — определяем по порядку величины
    if abs(re) > D(10) ** 20 or abs(im) > D(10) ** 20: inf = True
    if kind != "open" and abs(c) < D("1e-40") and kind == "short": inf = True
    if inf:
        out.append("Входное сопротивление Zinне ограничено — резонанс линии (разомкнутая цепь на входе)")
        out.append("Эквивалентные L и Cне определены — реактивность не ограничена")
        out.append("Знак реактивностименяется при переходе через эту длину: по одну сторону индуктивная, по другую ёмкостная")
        out.append("СтатусОценка: при этой длине входное сопротивление не ограничено (резонанс линии); по обе стороны от неё реактивность имеет противоположные знаки")
    else:
        if abs(im) < D("1e-12") * sc: im = D(0)
        rs = "свыше 1 ГОм (не ограничено)" if re >= 10 ** 9 else sv(re, "Ом")
        is_ = "свыше 1 ГОм (не ограничено)" if abs(im) >= 10 ** 9 else sv(abs(im), "Ом")
        zs = rs + (" − j" if im < 0 else " + j") + is_
        out.append("Входное сопротивление Zin = R + jX" + zs)
        kind_ = "чисто активное" if im == 0 else ("индуктивное (X > 0)" if im > 0 else "ёмкостное (X < 0)")
        out.append("Характер реактивности" + kind_)
        big = re >= 10 ** 9 or abs(im) >= 10 ** 9
        if re == 0 and im == 0:
            out.append("Модуль и фаза Zin0; фаза не определена (Zin = 0)")
        elif not big:
            mag = (re * re + im * im).sqrt()
            # фаза: atan2 через math на float (эталон угла — HP atan не нужен: берём arctan из Decimal-ряда не реализован → используем float, 4 знака)
            import math
            ph = math.degrees(math.atan2(float(im), float(re)))
            out.append("Модуль и фаза Zin" + sv(mag, "Ом") + ", " + dbs(D(ph)))
        if f is not None:
            f = D(f)
            if im == 0: lc = "нет: сопротивление чисто активное"
            elif im > 0: lc = "последовательная индуктивность L = X/(2πf) = " + sv(im / (2 * PI * f), "Гн")
            else: lc = "последовательная ёмкость C = 1/(2πf·|X|) = " + sv(1 / (2 * PI * f * (-im)), "Ф")
            out.append("Эквивалентные L или C на частоте " + si(f, "Гц") + lc)
        else:
            out.append("Эквивалентные L или Cне оценены — частота не введена")
        vs = vswr_ref(z0, kind, R, X)
        if vs is None: vs = (D(1), None)
        out.append("Статус" + "Оценка: Zin = " + zs + ", " + kind_ + "; КСВ " + vtxt(vs[1]) + " (линия без потерь)")
    vs = vswr_ref(z0, kind, R, X) or (D(1), None)
    out.append("Модуль коэффициента отражения |Γ| (на нагрузке и на входе)" + dbs(vs[0]))
    out.append("КСВ на входе линии" + vtxt(vs[1]))
    if abs(t) >= 10 ** 6 or abs(c) < D("1e-40"):
        if abs(c) < D("1e-40"): out.append("tg βlне ограничен (βl = 90° + k·180°, четверть волны)")
        else: out.append("tg βl" + ("+" if t > 0 else "−") + "свыше миллиона по модулю (не ограничен)")
    else:
        out.append("tg βl" + (dbs(t) if abs(t) > D("1e-40") else "0"))
    return out

