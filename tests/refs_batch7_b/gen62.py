F62 = "byudzhet-radiolinii-friis.html"
LAM = lambda f: C0 / D(f)

def fspl(d, f):
    return 20 * lg(4 * PI * D(d) / LAM(f))

def budget(f, d, ptd, gt, gr, l1, l2, la=0, lk=0):
    fs = fspl(d, f)
    at = D(la) + D(lk) * D(d) / 1000
    pr = D(ptd) + D(gt) + D(gr) - D(l1) - D(l2) - fs - at
    eirp = D(ptd) - D(l1) + D(gt)
    return fs, at, pr, eirp

def r1(f, d, d1=None):
    lam = LAM(f); d = D(d); a = D(d1) if d1 is not None else d / 2
    return (lam * a * (d - a) / d).sqrt()

def rows_common(f, d, ptd, gt, gr, l1, l2, la=0, lk=0, d1=None, rng=False):
    lam = LAM(f); fs, at, pr, eirp = budget(f, d, ptd, gt, gr, l1, l2, la, lk)
    out = ["Длина волны λ = c/f" + si(lam, "м"),
           "Потери в свободном пространстве Lfs = 20·lg(4πd/λ)" + fmtnum(fs) + " дБ" + ((" на расстоянии " + si(d, "м")) if rng else ""),
           "ЭИИМ = Pt − Lф1 + Gt" + fmtnum(eirp) + " дБм (" + pw(eirp) + ")",
           "Уровень на входе приёмника Pr = Pt − Lф1 + Gt − Lfs − Lпогл + Gr − Lф2" + fmtnum(pr) + " дБм (" + pw(pr) + ")"]
    if D(la) + D(lk) > 0:
        out.append("Потери на поглощение и дождь Lпогл" + fmtnum(at) + " дБ")
    rr = r1(f, d, d1)
    out.append("Радиус первой зоны Френеля r1 = √(λ·d1·d2/(d1 + d2))" + (" в середине трассы" if d1 is None else " на расстоянии " + si(d1, "м") + " от передатчика") + si(rr, "м"))
    out.append("Просвет не менее 0,6·r1 (критерий ITU-R P.526 для гладких препятствий)" + si(D("0.6") * rr, "м"))
    return out, pr

